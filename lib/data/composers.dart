/// Represents a classical music composer with metadata.
class ComposerData {
  final String name;
  final String epoch;
  final int? birthYear;
  final int? deathYear;

  const ComposerData({
    required this.name,
    required this.epoch,
    this.birthYear,
    this.deathYear,
  });

  /// Returns formatted life years, e.g., "(1685-1750)" or "(1937-)" for living.
  String get lifeYears {
    if (birthYear == null) return '';
    if (deathYear == null) return '($birthYear–)';
    return '($birthYear–$deathYear)';
  }

  /// Returns display string with name and years, e.g., "Johann Sebastian Bach (1685-1750)".
  String get displayName => deathYear != null || birthYear != null
      ? '$name $lifeYears'
      : name;
}

